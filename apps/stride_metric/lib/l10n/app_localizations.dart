enum AppLanguage {
  english(Locale('en'), 'English'),
  turkish(Locale('tr'), 'Türkçe'),
  german(Locale('de'), 'Deutsch'),
  spanish(Locale('es'), 'Español'),
  french(Locale('fr'), 'Français'),
  italian(Locale('it'), 'Italiano'),
  portugueseBrazil(Locale('pt', 'BR'), 'Português (Brasil)'),
  japanese(Locale('ja'), '日本語'),
  korean(Locale('ko'), '한국어'),
  simplifiedChinese(Locale('zh', 'CN'), '简体中文'),
  russian(Locale('ru'), 'Русский'),
  dutch(Locale('nl'), 'Nederlands'),
  hindi(Locale('hi'), 'हिन्दी');

  const AppLanguage(this.locale, this.nativeName);

  final Locale locale;
  final String nativeName;

  String get tag => locale.countryCode == null
      ? locale.languageCode
      : '${locale.languageCode}_${locale.countryCode}';

  static List<Locale> get supportedLocales =>
      values.map((item) => item.locale).toList(growable: false);

  static AppLanguage fromTag(String? tag, {Locale? systemLocale}) {
    final normalized = (tag ?? '').replaceAll('-', '_').toLowerCase();
    if (normalized.isNotEmpty) {
      for (final language in values) {
        if (language.tag.toLowerCase() == normalized ||
            language.locale.languageCode.toLowerCase() == normalized) {
          return language;
        }
      }
    }
    final locale = systemLocale ?? PlatformDispatcher.instance.locale;
    if (locale.languageCode == 'pt') return portugueseBrazil;
    if (locale.languageCode == 'zh') return simplifiedChinese;
    return values.firstWhere(
      (item) => item.locale.languageCode == locale.languageCode,
      orElse: () => english,
    );
  }
}

class AppLocalizations {
  const AppLocalizations(this.language);

  final AppLanguage language;

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;

  String t(String key, {Map<String, Object?> args = const {}}) {
    final values = _copy[key];
    assert(values != null, 'Unknown localization key: $key');
    if (values == null) return key;
    assert(
      values.length == AppLanguage.values.length,
      'Localization key $key does not cover all languages.',
    );
    var value = values[language.index];
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return value;
  }

  String audience(Audience value) => t(switch (value) {
    Audience.women => 'women',
    Audience.men => 'men',
    Audience.child => 'child',
  });

  String unitName(LengthUnit value) => t(switch (value) {
    LengthUnit.mm => 'millimetres',
    LengthUnit.cm => 'centimetres',
    LengthUnit.inch => 'inches',
  });

  String widthName(String value) {
    final normalized = value.toLowerCase();
    if (normalized == 'narrow' || value == '偏窄') return t('narrow');
    if (normalized == 'wide' || value == '偏宽') return t('wide');
    return t('regular');
  }

  static Set<String> get keys => _copy.keys.toSet();

  static bool hasCompleteCoverage() => _copy.values.every(
    (values) =>
        values.length == AppLanguage.values.length &&
        values.every((value) => value.trim().isNotEmpty),
  );
}

extension AppLocalizationsContext on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AppLanguage.values.any(
    (item) => item.locale.languageCode == locale.languageCode,
  );

  @override
  Future<AppLocalizations> load(Locale locale) => SynchronousFuture(
    AppLocalizations(
      AppLanguage.fromTag(locale.toLanguageTag(), systemLocale: locale),
    ),
  );

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

